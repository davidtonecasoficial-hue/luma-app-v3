fun resolveLumaStrings(
    language: AppLanguage,
    systemLocale: Locale = Locale.getDefault()
): LumaStrings {
    return when (language) {
        AppLanguage.PT -> PortugueseStrings
        AppLanguage.EN -> EnglishStrings
        AppLanguage.ES -> SpanishStrings
        AppLanguage.FR -> FrenchStrings
        AppLanguage.SYSTEM -> when (systemLocale.language.lowercase()) {
            "en" -> EnglishStrings
            "es" -> SpanishStrings
            "fr" -> FrenchStrings
            else -> PortugueseStrings
        }
    }
}

val LocalLumaStrings = compositionLocalOf { PortugueseStrings }

@Composable
fun ProvideLumaStrings(
    language: AppLanguage,
    content: @Composable () -> Unit
) {
    val strings = remember(language) { resolveLumaStrings(language) }
    CompositionLocalProvider(LocalLumaStrings provides strings, content = content)
}
